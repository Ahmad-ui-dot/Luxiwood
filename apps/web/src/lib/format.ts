// Цены и даты форматирует словарь выбранного языка: t.price(8900), t.date("2026-10-31")

// Без фирменного названия модели: «Пуф-банкетка «Нигина»» → «Пуф-банкетка», «Кресло «Навруз»» → «Кресло»
export function furnitureTitle(name: string) {
  return name.replace(/\s*«[^»]*»/g, "").trim() || name;
}
